// Generates TypeScript types from the contract (M1-TECH-02; BR-LG-03 to 06; T-07).
//
//   node scripts/generate-types.ts          write contract/generated/*.ts
//   node scripts/generate-types.ts --check  fail if a committed file differs
//
// One file per OpenAPI document: the shared components, and each surface
// document (org-gateway). A surface document's types bundle the shared
// definitions it references.
//
// One generator, openapi-typescript, run through its Node API. Its one
// customization is the `transform` hook below, recorded as T-07 condition 1:
// it matches exactly the open-enum shape `anyOf: [{ enum: [...] }, { type: string }]`
// and emits the known values plus `(string & {})`, so an unknown value is
// accepted while the known ones stay visible. Nothing else post-processes the
// output, and the output is never edited by hand.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString, tsLiteral, tsUnion } from 'openapi-typescript';
import type { SchemaObject } from 'openapi-typescript';
import ts from 'typescript';

const contractRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** The shared components document the generated types come from. */
export const componentsDocument = resolve(contractRoot, 'conventions/components.openapi.yaml');

/** Where the generated types are committed. */
export const generatedFile = resolve(contractRoot, 'generated/components.ts');

/** Every OpenAPI document that generates types, and where each is committed. */
export const generatedDocuments: readonly { document: string; output: string; source: string }[] = [
  {
    document: componentsDocument,
    output: generatedFile,
    source: 'contract/conventions/components.openapi.yaml',
  },
  {
    document: resolve(contractRoot, 'org-gateway.openapi.yaml'),
    output: resolve(contractRoot, 'generated/org-gateway.ts'),
    source: 'contract/org-gateway.openapi.yaml',
  },
  {
    document: resolve(contractRoot, 'control-gateway.openapi.yaml'),
    output: resolve(contractRoot, 'generated/control-gateway.ts'),
    source: 'contract/control-gateway.openapi.yaml',
  },
];

const ANNOTATION_KEYS = new Set(['description', 'title', '$comment']);

/**
 * True for exactly the open-enum shape (NFR-WC-06): an `anyOf` of two branches,
 * the first holding only a string `enum`, the second only `type: string`.
 * Annotations beside `anyOf` are allowed; any other keyword is not.
 */
export function isOpenEnum(
  schema: unknown,
): schema is { anyOf: [{ enum: string[] }, { type: 'string' }] } {
  if (typeof schema !== 'object' || schema === null) return false;
  const keys = Object.keys(schema).filter((k) => !ANNOTATION_KEYS.has(k));
  if (keys.length !== 1 || keys[0] !== 'anyOf') return false;
  const anyOf = (schema as { anyOf: unknown }).anyOf;
  if (!Array.isArray(anyOf) || anyOf.length !== 2) return false;
  const [known, open] = anyOf as unknown[];
  if (typeof known !== 'object' || known === null || typeof open !== 'object' || open === null) {
    return false;
  }
  const knownKeys = Object.keys(known);
  const openKeys = Object.keys(open);
  const values = (known as { enum?: unknown }).enum;
  return (
    knownKeys.length === 1 &&
    knownKeys[0] === 'enum' &&
    Array.isArray(values) &&
    values.length > 0 &&
    values.every((v) => typeof v === 'string') &&
    openKeys.length === 1 &&
    openKeys[0] === 'type' &&
    (open as { type?: unknown }).type === 'string'
  );
}

/** The known values, plus `(string & {})`: any other string is accepted. */
function openEnumType(values: string[]): ts.TypeNode {
  const anyOtherString = ts.factory.createParenthesizedType(
    ts.factory.createIntersectionTypeNode([
      ts.factory.createKeywordTypeNode(ts.SyntaxKind.StringKeyword),
      ts.factory.createTypeLiteralNode([]),
    ]),
  );
  return tsUnion([...values.map((v) => tsLiteral(v)), anyOtherString]);
}

/** openapi-typescript's `transform` hook (T-07 condition 1). */
export function transform(schemaObject: SchemaObject): ts.TypeNode | undefined {
  return isOpenEnum(schemaObject) ? openEnumType(schemaObject.anyOf[0].enum) : undefined;
}

function header(source: string): string {
  return [
    '// SPDX-License-Identifier: Apache-2.0',
    `// Generated by contract/scripts/generate-types.ts from ${source}.`,
    '// Do not edit: change the schema, then run `pnpm run generate`.',
    '',
    '',
  ].join('\n');
}

/** Generates the types for one OpenAPI document. Deterministic: same input, same bytes. */
export async function generate(documentPath: string, sourceLabel: string): Promise<string> {
  const ast = await openapiTS(pathToFileURL(documentPath), { transform, silent: true });
  const body = astToString(ast).replace(/\r\n/g, '\n');
  return header(sourceLabel) + body.trimEnd() + '\n';
}

/** The drift check: undefined when the committed file is what the schemas generate. */
export function driftMessage(
  committed: string,
  generated: string,
  file = 'contract/generated/components.ts',
): string | undefined {
  if (committed === generated) return undefined;
  return (
    `${file} differs from what the schemas generate. ` +
    'Run `pnpm run generate` and commit the result; never edit generated files by hand.'
  );
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check');
  for (const { document, output: outFile, source } of generatedDocuments) {
    const output = await generate(document, source);
    const label = `contract/${relative(contractRoot, outFile)}`;
    if (check) {
      const committed = await readFile(outFile, 'utf8').catch(() => '');
      const drift = driftMessage(committed, output, label);
      if (drift) {
        console.error(drift);
        process.exitCode = 1;
        continue;
      }
      console.log(`${label} matches the schemas.`);
      continue;
    }
    await mkdir(dirname(outFile), { recursive: true });
    await writeFile(outFile, output);
    console.log(`Wrote ${label}`);
  }
}

if (import.meta.main) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
